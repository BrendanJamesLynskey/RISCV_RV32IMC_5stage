#!/usr/bin/env python3
"""Tables for doc/branch_prediction.md from the bp_sweep.sh counters.

Usage: bp_report.py [tests/bench/build/bp]

Window = the cycles between a BENCH_MARK pair (2k, 2k+1), as bench_report.py.
Instructions = retired between the markers, less the end marker. Branches and
mispredicts are counted when the branch resolves in EX, two stages before the
marker's own retirement, so a window can pick up or lose a branch or two at
its edges; the whole-program totals are exact.

Misses are conditional branches (and hardware-loop ends) only: JAL/JALR never
train the predictor and always cost two bubbles whatever kind is chosen
(bench "jump" column).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bench_report  # noqa: E402
import cpi_breakdown  # noqa: E402

D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "build", "bp")
KIND = {0: "static not-taken", 1: "1-bit", 2: "2-bit (default)", 3: "gshare", 4: "tournament"}
KBEGIN = {n: b for b, n, _, _ in bench_report.KERNELS}
SET = [n for n, _ in cpi_breakdown.SET]
KEM = [("KeyGen", 0), ("Encaps", 2), ("Decaps", 4)]


def read(path):
    marks, end = {}, None
    for line in open(path):
        f = line.split()
        if f[0] == "end":
            end = [int(x) for x in f[1:]]
        else:
            marks.setdefault(int(f[0]), [int(x) for x in f[1:]])
    return marks, end


def window(marks, b):
    """cycles, instrs, branches, cond mispredicts, jump mispredicts, other mispredicts"""
    a, z = marks[b], marks[b + 1]
    return (z[0] - a[0], z[1] - a[1] - 1, z[2] - a[2], z[3] - a[3], z[4] - a[4], z[5] - a[5])


def load():
    res = {}
    for name in sorted(os.listdir(D)):
        if not name.startswith("k") or not os.path.exists(os.path.join(D, name, "kem_ext.stats")):
            continue
        k, b, g = (int(x[1:]) for x in name.split("_"))
        r = {}
        for prog in ("dsp", "kem_ref", "kem_ext"):
            r[prog] = read(os.path.join(D, name, prog + ".stats"))
        res[(k, b, g)] = r
    return res


def rows(r):
    """{label: window} for the E1 set plus three ML-KEM-512 operations on each back end"""
    out = {}
    for n in SET:
        out[n] = window(r["dsp"][0], KBEGIN[n])
    for be in ("ref", "ext"):
        for n, b in KEM:
            out[f"ML-KEM-512 {be} {n}"] = window(r["kem_" + be][0], b)
    return out


def total(w):
    return tuple(sum(x[i] for x in w.values()) for i in range(6))


def label(k, b, g):
    return KIND[k] + (f", {b} entries" if k else "") + (f", history {g}" if k >= 3 else "")


def summary(res, keys, title):
    print(f"\n{title}\n")
    print("| predictor | cond. branches | mispredicts | per branch | per 1,000 instr | CPI | cycles vs 2-bit | 2 x mispredict change |")
    print("|---|--:|--:|--:|--:|--:|--:|--:|")
    base = total(rows(res[(2, 256, 0)]))
    for key in keys:
        t = total(rows(res[key]))
        cyc, ins, br, mp = t[0], t[1], t[2], t[3]
        print(f"| {label(*key)} | {br} | {mp} | {mp / br:.3%} | {1000 * mp / ins:.2f} | {cyc / ins:.4f} | "
              f"{cyc - base[0]:+d} | {2 * (mp + t[4] + t[5] - base[3] - base[4] - base[5]):+d} |")


def perkernel(res, keys, what):
    print(f"\n{what}\n")
    print("| benchmark | branches / 1,000 instr | " + " | ".join(
        label(*k).replace(", 256 entries", "").replace(", history 8", "") for k in keys) + " |")
    print("|---|--:|" + "--:|" * len(keys))
    allr = [rows(res[k]) for k in keys]
    for n in allr[0]:
        w0 = allr[0][n]
        cells = []
        for rr in allr:
            w = rr[n]
            cells.append(f"{1000 * w[3] / w[1]:.1f} / {w[0] / w[1]:.3f}")
        print(f"| {n} | {1000 * w0[2] / w0[1]:.0f} | " + " | ".join(cells) + " |")


def main():
    res = load()
    print("<!-- generated by bp_report.py -->")
    summary(res, [k for k in [(0, 256, 0), (1, 256, 0), (2, 256, 0), (3, 256, 8), (4, 256, 8)] if k in res],
            "Whole benchmark set, every kind (256-entry tables, history 8 where it applies)")
    summary(res, [k for k in [(2, 64, 0), (2, 256, 0), (2, 1024, 0), (3, 64, 6), (3, 256, 8), (3, 1024, 10)] if k in res],
            "Table size (history as long as the index)")
    summary(res, [k for k in sorted(res) if k[0] == 3], "gshare: table size and history length")
    keys = [k for k in [(0, 256, 0), (1, 256, 0), (2, 256, 0), (3, 256, 8), (4, 256, 8)] if k in res]
    perkernel(res, keys, "Per benchmark: mispredicts per 1,000 instructions / CPI")


if __name__ == "__main__":
    main()
