#!/usr/bin/env python3
"""Generate the whole-ML-KEM benchmark's seeds and expected outputs (kem_data.h).

    gen_kem.py > kem_data.h

ML-KEM-512 (FIPS 203: k = 2, eta1 = 3, eta2 = 2, du = 10, dv = 4), from the
model in mlkem.py in its final form (draft=False, the one that passes NIST's
ACVP vectors). The seeds d, z and m come from the same fixed LCG as
gen_data.py's inputs, so the header is reproducible. kem_main.c runs
KeyGen(d, z), Encaps(ek, m) and Decaps(dk, c) on the core and compares ek,
dk, c and K byte for byte. A fourth case is Decaps of a tampered ciphertext
(one byte of c changed), whose result must be the implicit-rejection key
J(z || c'), not K: the model checks that it is before writing it out.

keccak: test vectors for keccak.c, from hashlib: SHA3-256 and SHA3-512 of
        the empty message and of a 200-byte message, and 300 bytes of
        SHAKE128 and SHAKE256 of the same message (300 bytes spans two
        blocks of either rate, so the squeeze is checked across a
        permutation).
"""
import hashlib
import mlkem

LEVEL = 512
P = mlkem.PARAMS[LEVEL]


def lcg(seed):
    while True:
        seed = (1103515245 * seed + 12345) & 0x7FFFFFFF
        yield seed


def rand_bytes(n, seed):
    g = lcg(seed)
    return bytes((next(g) >> 16) & 0xFF for _ in range(n))


def arr(name, vals):
    rows = [", ".join(f"0x{v:02x}" for v in vals[i:i + 12]) for i in range(0, len(vals), 12)]
    return f"static const uint8_t {name}[{len(vals)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    d, z, m = rand_bytes(32, 61), rand_bytes(32, 67), rand_bytes(32, 71)
    ek, dk = mlkem.keygen(d, z, P)
    K, c = mlkem.encaps(ek, m, P)
    assert mlkem.decaps(dk, c, P) == K, "decapsulation does not recover K"
    bad = bytearray(c)
    bad[100] ^= 0x5A                                      # in c1: u's compressed coefficients
    bad = bytes(bad)
    K_bad = mlkem.decaps(dk, bad, P)
    assert K_bad != K and K_bad == mlkem.J(z + bad), "the tampered ciphertext is not rejected"

    msg = rand_bytes(200, 73)
    print("/* kem_data.h: generated by gen_kem.py; do not edit. */")
    print(f"#define KEM_K {P[0]}\n#define KEM_ETA1 {P[1]}\n#define KEM_ETA2 {P[2]}\n"
          f"#define KEM_DU {P[3]}\n#define KEM_DV {P[4]}\n"
          f"#define KEM_EK_BYTES {len(ek)}\n#define KEM_DK_BYTES {len(dk)}\n#define KEM_CT_BYTES {len(c)}\n")
    for name, v in (("kem_d", d), ("kem_z", z), ("kem_m", m), ("kem_ek_expect", ek), ("kem_dk_expect", dk),
                    ("kem_ct_expect", c), ("kem_key_expect", K), ("kem_ct_bad", bad), ("kem_key_bad_expect", K_bad)):
        print(arr(name, v))
    print(arr("kat_msg", msg))
    print(arr("kat_sha3_256_empty", hashlib.sha3_256(b"").digest()))
    print(arr("kat_sha3_256", hashlib.sha3_256(msg).digest()))
    print(arr("kat_sha3_512", hashlib.sha3_512(msg).digest()))
    print(arr("kat_shake128", hashlib.shake_128(msg).digest(300)))
    print(arr("kat_shake256", hashlib.shake_256(msg).digest(300)))


if __name__ == "__main__":
    main()
